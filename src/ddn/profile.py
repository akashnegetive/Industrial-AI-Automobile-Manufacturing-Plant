"""Part B.1 - profile every dataset.

For each file we report the four things the assignment asks for:
  size, keys, time coverage, and how the file identifies equipment.

Run:  python -m ddn.profile      (writes reports/01_dataset_profile.md)
"""
from __future__ import annotations

import pandas as pd

from .config import REPORTS
from .load import SPECS, load

# Hand-written metadata: the key we *expect* to be unique, and which column(s)
# point at equipment. This is domain knowledge from the data dictionary; the
# profiler then checks it against the real data.
