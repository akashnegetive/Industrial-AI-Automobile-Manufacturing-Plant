def profile_one(name: str, df: pd.DataFrame) -> dict:
    meta = META[name]
    dates = SPECS[name][0]
    key = meta["key"]
    dup_keys = int(df.duplicated(subset=key).sum())
    full_dups = int(df.duplicated().sum())

    # time coverage = min/max of the main timestamp column, if any
    time_col = next((c for c in dates if c != "install_date"), None)
    coverage = (
        f"{df[time_col].min():%Y-%m-%d %H:%M} → {df[time_col].max():%Y-%m-%d %H:%M}"
        if time_col else "—"
    )
    nulls = (df.isna().mean() * 100).round(1)
    nulls = nulls[nulls > 0].sort_values(ascending=False)

    return {
        "file": name,
        "rows": len(df),
        "cols": df.shape[1],
        "key": " + ".join(key),
        "key_unique": dup_keys == 0,
        "dup_keys": dup_keys,
        "full_dup_rows": full_dups,
        "time_col": time_col or "—",
        "coverage": coverage,
        "nulls": nulls.to_dict(),
        "equip_cols": meta["equip"],
        "how": meta["how"],
        "examples": {
            c: df[c].dropna().drop_duplicates().head(3).tolist() for c in meta["equip"]
        },
        "columns": list(df.columns),
    }


def to_markdown(profiles: list[dict]) -> str:
    out = ["# Part B.1 – Dataset profiles", "",
           "Generated by `python -m ddn.profile`. Do not edit by hand.", "",
           "## Summary", "",
           "| File | Rows | Cols | Expected key | Key unique? | Duplicate keys | Exact duplicate rows | Time coverage |",
           "|---|---:|---:|---|---|---:|---:|---|"]
    for p in profiles:
        out.append(
            f"| `{p['file']}` | {p['rows']:,} | {p['cols']} | `{p['key']}` | "
            f"{'yes' if p['key_unique'] else '**NO**'} | {p['dup_keys']:,} | "
            f"{p['full_dup_rows']:,} | {p['coverage']} |"
        )
    out += ["", "## How each dataset identifies equipment", "",
            "| File | Equipment columns | How | Example values |", "|---|---|---|---|"]
    for p in profiles:
        ex = "; ".join(f"{c}: {', '.join(map(str, v))}" for c, v in p["examples"].items())
        out.append(f"| `{p['file']}` | {', '.join(p['equip_cols']) or '—'} | {p['how']} | {ex or '—'} |")
    out += ["", "## Per-file detail", ""]
    for p in profiles:
        out += [f"### `{p['file']}`", "",
                f"- Columns: {', '.join(f'`{c}`' for c in p['columns'])}",
                f"- Missing values (% of rows): "
                + (", ".join(f"`{k}` {v}%" for k, v in p["nulls"].items()) or "none"),
                ""]
    return "\n".join(out)


def main() -> None:
    profiles = []
    for name in SPECS:
        df = load(name)
        profiles.append(profile_one(name, df))
        print(f"profiled {name:40s} {len(df):>10,} rows")
    REPORTS.mkdir(exist_ok=True)
    path = REPORTS / "01_dataset_profile.md"
    path.write_text(to_markdown(profiles), encoding="utf-8")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
