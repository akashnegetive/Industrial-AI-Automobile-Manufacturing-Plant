"""Part C8 - measure matcher quality against engineer-confirmed labels.

Definitions (per record, e.g. per tag):
    TP  predicted asset == true asset
    FP  predicted an asset, but the wrong one          (dangerous: a wrong edge)
    FN  true asset exists, but predicted nothing or the wrong one
    precision = TP / (TP + FP)    "when we link, how often are we right?"
    recall    = TP / (TP + FN)    "how many true links do we find?"
    F1        = harmonic mean of the two (the assignment target is >= 0.85)

A wrong prediction counts as both FP and FN: it creates a bad edge AND misses
the right one.

Run:  python -m ddn.evaluate     (writes reports/05_matching_rules_baseline.md)
"""
from __future__ import annotations

import pandas as pd

from .config import REPORTS, STAGING
from .load import load
from .match_rules import RulesMatcher, WorkOrderRulesMatcher


def score(pred: pd.DataFrame, truth: pd.DataFrame, key: str = "tag_name") -> dict:
    """pred: key, functional_location (None = no link). truth: key, functional_location."""
    m = truth.merge(pred[[key, "functional_location"]], on=key, how="left", suffixes=("_true", "_pred"))
    has_pred = m.functional_location_pred.notna()
    correct = has_pred & (m.functional_location_pred == m.functional_location_true)
    tp, fp = int(correct.sum()), int((has_pred & ~correct).sum())
    fn = len(m) - tp
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * p * r / (p + r) if p + r else 0.0
    return {"n": len(m), "tp": tp, "fp": fp, "fn": fn, "precision": p, "recall": r, "f1": f1}


def score_by(pred: pd.DataFrame, truth: pd.DataFrame, group: pd.Series, key: str = "tag_name") -> pd.DataFrame:
    rows = []
    for g in sorted(group.dropna().unique()):
        keys = group[group == g].index
        rows.append({"group": g, **score(pred, truth[truth[key].isin(keys)], key)})
    rows.append({"group": "ALL", **score(pred, truth, key)})
    return pd.DataFrame(rows)


def _fmt(df: pd.DataFrame) -> str:
    out = ["| Group | n | TP | FP | FN | Precision | Recall | F1 |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for r in df.itertuples():
        out.append(f"| {r.group} | {r.n} | {r.tp} | {r.fp} | {r.fn} | {r.precision:.3f} | {r.recall:.3f} | {r.f1:.3f} |")
    return "\n".join(out)


def main() -> None:
    tags = pd.read_parquet(STAGING / "tags.parquet")
    assets = pd.read_parquet(STAGING / "assets.parquet")
    truth = load("labels_tag_to_asset_TRAIN.csv")

    pred = RulesMatcher(assets).match_all(tags)
    pred.to_parquet(STAGING / "tag_matches_rules.parquet", index=False)

    by_source = score_by(pred, truth, tags.set_index("tag_name").source_system)
    by_method = score_by(pred, truth, pred.set_index("tag_name").method)
    m = truth.merge(pred, on="tag_name", suffixes=("_true", "_pred")).merge(tags, on="tag_name")
    wrong = m[m.functional_location_pred.notna() & (m.functional_location_pred != m.functional_location_true)]
    missed = m[m.functional_location_pred.isna()]
    coverage = pred.functional_location.notna().mean()

    # ---- work orders --------------------------------------------------------------
    wos = load("maintenance_work_orders.csv")
    wo_truth = load("labels_workorder_to_asset_TRAIN.csv")
    wo_pred = WorkOrderRulesMatcher(assets).match_all(wos)
    wo_pred.to_parquet(STAGING / "wo_matches_rules.parquet", index=False)
    wo_by_method = score_by(wo_pred, wo_truth, wo_pred.set_index("wo_number").method, key="wo_number")
    wm = wo_truth.merge(wo_pred, on="wo_number", suffixes=("_true", "_pred")).merge(wos, on="wo_number")
    wo_wrong = wm[wm.functional_location_pred.notna() & (wm.functional_location_pred != wm.functional_location_true)]
    wo_cov = wo_pred.functional_location.notna().mean()

    out = ["# Part C – Rules-only baseline (tags and work orders)", "",
           "Generated by `python -m ddn.evaluate`. Scored on the engineer-confirmed TRAIN labels "
           f"({len(truth)} tags). The rules use no training data, but they were *designed* after reading the TRAIN "
           "labels (which hierarchy level a tag belongs to) and one bug (zero padding of P1) was fixed after "
           "looking at TRAIN failures. TRAIN scores are therefore slightly optimistic; the hidden test set is "
           "the real measure.", "",
           f"**Coverage:** {coverage:.1%} of all {len(tags):,} tags get a link "
           f"({pred.functional_location.notna().sum():,} tags).", "",
           "## By source system", "", _fmt(by_source), "",
           "## By rule (method)", "", _fmt(by_method), "",
           f"## Wrong links ({len(wrong)})", "",
           "These are the dangerous errors: an edge that would enter the graph and be wrong.", "",
           "| Tag | Predicted | Truth | Rule |", "|---|---|---|---|"]
    out += [f"| `{r.tag_name}` | `{r.functional_location_pred}` | `{r.functional_location_true}` | {r.method} |"
            for r in wrong.itertuples()]
    out += ["", f"## Missed links ({len(missed)}) – why the rules gave up", "",
            "| Reason | Count | Examples |", "|---|---:|---|"]
    for reason, g in missed.groupby(missed.reason.str.replace(r" for key .*| [A-Z]+/.*", "", regex=True)):
        out.append(f"| {reason} | {len(g)} | {', '.join(f'`{t}`' for t in g.tag_name.head(5))} |")
    out += ["", "### Every missed tag", "", "| Tag | Parsed as (shop/line/equip) | Truth |", "|---|---|---|"]
    out += [f"| `{r.tag_name}` | {r.shop}/{r.line}/{r.equip} | `{r.functional_location_true}` |" for r in missed.itertuples()]
    out += ["", "# Work orders", "",
            f"Scored on {len(wo_truth)} TRAIN work orders. Rules use only `functional_location_text` and "
            "`equipment_no`, never the free text.", "",
            f"**Coverage:** {wo_cov:.1%} of all {len(wos):,} work orders get a link.", "",
            "## By rule (method)", "", _fmt(wo_by_method), "",
            f"## Wrong links ({len(wo_wrong)}) – mostly a wrong SAP equipment number", "",
            "| WO | Rule | Predicted | Truth | Short text |", "|---|---|---|---|---|"]
    out += [f"| {r.wo_number} | {r.method} | `{r.functional_location_pred}` | `{r.functional_location_true}` | "
            f"{r.short_text} |" for r in wo_wrong.head(15).itertuples()]
    out += ["", "*Lesson:* a source-system key is not ground truth. The equipment number must be cross-checked "
            "against the text before it is trusted (done by the ML matcher on Day 5)."]
    path = REPORTS / "05_matching_rules_baseline.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")

    w = wo_by_method.iloc[-1]
    print(f"work orders:    P={w.precision:.3f} R={w.recall:.3f} F1={w.f1:.3f} coverage={wo_cov:.1%} wrong={len(wo_wrong)}")
    allr = by_source.iloc[-1]
    print(f"tags:           P={allr.precision:.3f} R={allr.recall:.3f} F1={allr.f1:.3f} "
          f"coverage={coverage:.1%} wrong={len(wrong)} missed={len(missed)} -> {path}")


if __name__ == "__main__":
    main()
